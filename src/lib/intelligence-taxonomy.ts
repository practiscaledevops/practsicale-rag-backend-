/** Ref prefix for an object (MG-001, DEC-014, PI-LI-003 …). */
export function refPrefix(o: {
  intelligence_class: IntelligenceClass;
  domain?: string | null;
  object_type?: string | null;
}): string {
  if (o.intelligence_class === "organizational_learning") {
    return LEARNING_REF_PREFIX[o.object_type ?? ""] ?? "LRN";
  }
  if (o.intelligence_class === "platform_intelligence") {
    const p = (o.domain === "platform" ? "" : o.domain ?? "").toUpperCase().slice(0, 2);
    return p ? `PI-${p}` : "PI";
  }
  if (o.intelligence_class === "performance_memory") return "PERF";
  if (o.intelligence_class === "raw_archive") return "RAW";
  const dom = DOMAINS.find((d) => d.id === o.domain)?.prefix ?? "GEN";
  return o.intelligence_class === "business_reality" ? `BR-${dom}` : dom;
}

/** Format a ref from a prefix and a sequence number: MG + 7 → "MG-007". */
export function formatRef(prefix: string, n: number): string {
  return `${prefix}-${String(Math.max(1, Math.floor(n))).padStart(3, "0")}`;
}

/** Lower-case snake slug for taxonomy values ("Management Leverage" → "management_leverage"). */
export function slugify(s: string): string {
  return (s || "")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 64);
}

/** "management_leverage" → "Management leverage". */
export function humanize(s: string): string {
  const t = (s || "").replace(/[_-]+/g, " ").trim();
  return t ? t.charAt(0).toUpperCase() + t.slice(1) : "";
}

/** Jaccard-ish similarity of two slugs' token sets, for taxonomy reconciliation. */
export function slugSimilarity(a: string, b: string): number {
  const ta = new Set(slugify(a).split("_").filter(Boolean));
  const tb = new Set(slugify(b).split("_").filter(Boolean));
  if (ta.size === 0 || tb.size === 0) return 0;
  let inter = 0;
  for (const t of ta) if (tb.has(t)) inter++;
  const union = ta.size + tb.size - inter;
  const jac = inter / union;
  // Prefix containment bonus: "delegation" vs "delegation_rights".
  const sa = slugify(a);
  const sb = slugify(b);
  const contains = sa.length >= 4 && (sb.startsWith(sa) || sa.startsWith(sb)) ? 0.2 : 0;
  return Math.min(1, jac + contains);
}

/** Pick the closest existing taxonomy value for a proposed one, or null if nothing fits. */
export function reconcileValue(
  proposed: string,
  existing: string[],
  threshold = 0.6
): { value: string; similarity: number } | null {
  const p = slugify(proposed);
  if (!p) return null;
  let best: { value: string; similarity: number } | null = null;
  for (const e of existing) {
    if (slugify(e) === p) return { value: e, similarity: 1 };
    const sim = slugSimilarity(p, e);
    if (sim >= threshold && (!best || sim > best.similarity)) best = { value: e, similarity: sim };
  }
  return best;
}
