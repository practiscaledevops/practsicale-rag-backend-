/**
 * Default authority for an object from its class + governance fields. Authority
 * tells the Brain what to TRUST; the temporal fields tell it whether that trust
 * is still current (see isCurrent()).
 */
export function defaultAuthority(o: {
  intelligence_class: IntelligenceClass;
  domain?: string | null;
  object_type?: string | null;
  status?: string | null;
  founder_endorsement?: string | null;
  internal_validation?: string | null;
  source_platform?: string | null;
  bucket?: RealityBucket | null;
}): AuthorityLevel {
  if (o.status === "archived") return "C3";
  if (o.status === "historical") return "C1";
  switch (o.intelligence_class) {
    case "raw_archive":
      return "C2";
    case "organizational_learning":
      return o.internal_validation === "validated" || o.object_type === "standard" ? "A2" : "A5";
    case "playbook":
      if (o.founder_endorsement === "practiscale_standard") return "B1";
      if (o.internal_validation === "validated") return "B1";
      if (o.founder_endorsement === "approved") return "B2";
      return "B3";
    case "platform_intelligence":
      return o.internal_validation === "validated" ? "A2" : "B3";
    case "performance_memory":
      return "A2";
    case "business_reality": {
      const bucket = o.bucket ?? realityBucketOf(o);
      return REALITY_BUCKETS.find((b) => b.id === bucket)?.authority ?? "A2";
    }
    default:
      return "B3";
  }
}

/** Whether an object is current given its temporal fields (as of `now`). */
export function isCurrent(
  o: { effective_from?: string | null; effective_until?: string | null; status?: string | null },
  now: Date = new Date()
): boolean {
  if (o.status === "historical" || o.status === "archived") return false;
  const t = now.getTime();
  if (o.effective_from && new Date(o.effective_from).getTime() > t) return false;
  if (o.effective_until && new Date(o.effective_until).getTime() <= t) return false;
  return true;
}

