// The Operating Intelligence taxonomy — the ONE classification system for every
// knowledge object in the Brain:  CLASS → DOMAIN → TYPE → SUBTYPE (+ open tags).
//
// Three core intelligence classes (Business Reality / Playbooks / Organizational
// Learning) plus two supporting systems (Platform Intelligence / Performance
// Memory). Domain and Type are predefined; Subtype is controlled-but-extensible
// (the compiler reuses existing values and proposes new ones into an approval
// queue); Tags are completely open.
//
// Pure data + helpers — safe to import from client components and the server.
// Persisted extensions (proposed/approved subtypes etc.) live in taxonomy_values.

