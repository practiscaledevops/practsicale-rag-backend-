/** Infer the human-facing bucket of a reality object from its classification. */
export function realityBucketOf(o: {
  domain?: string | null;
  object_type?: string | null;
  status?: string | null;
}): RealityBucket {
  if (o.status === "historical" || o.status === "archived") return "historical_archive";
  const t = o.object_type ?? "";
  if (t === "testimonial" || t === "case_study" || t === "proof") return "proof_evidence";
  if (t === "approved_content") return "approved_content";
  switch (o.domain) {
    case "company":
    case "finance":
    case "legal":
    case "technology":
      return "company_truth";
    case "founder":
      return "founder_brain";
    case "customer":
    case "customer_success":
      return "customer_intelligence";
    case "sales":
    case "offers":
      return "sales_intelligence";
    case "operations":
      return "operations_intelligence";
    case "people_management":
    case "management":
    case "talent_hiring":
    case "leadership":
      return "people_management";
    case "brand":
      return "brand_voice";
    case "content":
    case "marketing":
      return "approved_content";
    default:
      return "company_truth";
  }
}

